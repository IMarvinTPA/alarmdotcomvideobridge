import asyncio
import logging
from aiortc import RTCPeerConnection, RTCSessionDescription, RTCIceCandidate, RTCConfiguration
from aiortc.sdp import candidate_from_sdp, candidate_to_sdp
from websocketsignaling import WebsocketSignaling
from typing import Dict, Optional

logger = logging.getLogger("webrtc-rtsp-cli.janus-orchestrator")

class AlarmJanusOrchestrator:
    """
    Manages the transactional state machine for Alarm.com's custom Janus Gateway.
    Orchestrates Session Creation, Dynamic Stream Injection, Watch Requests,
    and JSEP Offer/Answer renegotiation over a single custom WebsocketSignaling channel.
    """
    def __init__(self, custom_signal: WebsocketSignaling,
                 janus_token: str,
                 proxy_url: str,
                 resolution: str,
                 requestedCameraId: str,
                 cameraMacAddress: str,
                 cameraModel: str,
                 cameraFirmwareVersion: str,
                 ) -> None:
        self.signal = custom_signal
        self.proxy_url = proxy_url
        self.resolution = resolution
        self.current_transaction = 0
        self.requestedCameraId = requestedCameraId
        self.cameraMacAddress = cameraMacAddress
        self.cameraModel = cameraModel
        self.cameraFirmwareVersion = cameraFirmwareVersion
        self.webrtc_up = False

        # Connection Context States
        self.session_id = None
        self.handle_id = None
        self.dynamic_stream_id = None
        self.src_pc = None
        self.token = janus_token  # The compound Janus Auth Token string
        self.is_running = False
        self.transaction_intent: Dict[int, str] = {}

    def getNextTransactionId(self, intent: str) -> str:
        val = str(self.current_transaction)
        self.transaction_intent[val] = intent
        self.current_transaction += 1
        return val

    async def initialize_peer_connection(self,
                                         on_track_cb,
                                         on_state_change_cb,
                                         configuration: Optional[RTCConfiguration] = None,
                                         ) -> RTCPeerConnection:
        """Instantiates the standard local aiortc PeerConnection."""
        self.src_pc = RTCPeerConnection(configuration)

        # Register external pipeline tracking callbacks
        self.src_pc.add_listener("track", on_track_cb)
        self.src_pc.add_listener("connectionstatechange", on_state_change_cb)

        # Handle local ICE candidates generated by aiortc and trickle them upstream
        @self.src_pc.on("icecandidate")
        async def on_icecandidate(candidate):
            if candidate and self.session_id and self.handle_id:
                candidate_str = candidate_to_sdp(candidate)
                trickle_payload = {
                    "session_id": self.session_id,
                    "janus": "trickle",
                    "transaction": self.getNextTransactionId("trickle_cand"),
                    "token": self.token,
                    "handle_id": self.handle_id,
                    "candidate": {
                        "candidate": f"candidate:{candidate_str}",
                        "sdpMid": candidate.sdpMid,
                        "sdpMLineIndex": candidate.sdpMLineIndex,
                        "usernameFragment": self.src_pc.localDescription.iceUfrag if self.src_pc.localDescription else None
                    }
                }
                logger.info("Trickling local ICE candidate upstream to Janus.")
                await self.signal.send_json(trickle_payload)

        return self.src_pc

    async def start_pipeline(self) -> None:
        """Executes the synchronous initialization sequence (Sent 1 through Sent 4)."""
        self.is_running = True

        # ─── SENT 1: CREATE SESSION ───
        logger.info("Sent 1: Creating Janus Core Session Container.")
        await self.signal.send_json({
            "janus": "create",
            "transaction": self.getNextTransactionId("create"),
            "token": self.token,
            "request": "create"
        })

        # Process responses iteratively until we acquire our IDs and can bind the listener loop
        asyncio.create_task(self.__inbound_event_listener_loop())

        self._keepalive_task = asyncio.create_task(self.__janus_keepalive_loop())

    async def __inbound_event_listener_loop(self) -> None:
        """Asynchronously parses and routes backend events and JSEP negotiations dynamically."""
        try:
            local_answer_desc = None
            candidates_done = False
            while self.is_running and not self.signal.closed:
                raw_msg = await self.signal.receive_json()
                if not raw_msg or not isinstance(raw_msg, dict):
                    await asyncio.sleep(0.1)
                    continue

                janus_event = raw_msg.get("janus")
                transaction = raw_msg.get("transaction")
                transaction_intent = self.transaction_intent.get(transaction, "Unknown")

                if transaction_intent == "keepalive":
                    if janus_event == "ack":
                        logger.debug(f"Janus Keepalive response confirmed for session {self.session_id}")
                    # Pop it from your tracking map defensively to keep dictionary footprints tiny
                    self.transaction_intent.pop(transaction, None)
                    continue

                elif janus_event == "webrtcup":
                    logger.info("─── JANUS MEDIA TRANSPORT ACTIVE ───")
                    logger.info(f"Session: {raw_msg.get('session_id')} | Sender (Handle): {raw_msg.get('sender')}")
                    self.webrtc_up = True

                # ─── RECEIVED 1: SESSION CREATED ───
                elif transaction_intent == "create" and janus_event == "success":
                    self.session_id = raw_msg["data"]["id"]
                    logger.info(f"Received 1: Session validated successfully. ID assigned: {self.session_id}")

                    # ─── SENT 2: ATTACH TO STREAMING PLUGIN ───
                    logger.info("Sent 2: Attaching plugin profile handles.")
                    await self.signal.send_json({
                        "session_id": self.session_id,
                        "janus": "attach",
                        "transaction": self.getNextTransactionId("attach"),
                        "token": self.token,
                        "plugin": "janus.plugin.streaming",
                        "force-bundle": True,
                        "force-rtcp-mux": True,
                        "opaque_id": f"webrtc-player_{self.requestedCameraId}"
                    })

                # ─── RECEIVED 2: PLUGIN ATTACHED ───
                elif transaction_intent == "attach" and janus_event == "success":
                    self.handle_id = raw_msg["data"]["id"]
                    logger.info(f"Received 2: Plugin bound natively. Handle ID: {self.handle_id}")

                    # ─── SENT 3: CREATE DYNAMIC STREAM listener ───
                    logger.info("Sent 3: Injecting temporary transient media proxy configuration.")
                    await self.signal.send_json({
                        "session_id": self.session_id,
                        "janus": "message",
                        "transaction": self.getNextTransactionId("inject"),
                        "token": self.token,
                        "handle_id": self.handle_id,
                        "body": {
                            "request": "create",
                            "is_private": True,
                            "type": "rtp",
                            "media_uri": self.proxy_url,
                            "add_sps_pps": False,
                            "is_virtual": False,
                            "streaming_type": "Live",
                            "timeout_seconds": 180,
                            "max_timeout_seconds": 900,
                            "video": True,
                            "videoport": 0,
                            "videopt": 126,
                            "videortpmap": "H264/90000",
                            "videofmtp": "profile-level-id=42e01f;packetization-mode=1",
                            "name": self.cameraMacAddress + "_Live",
                            "model": self.cameraModel,
                            "firmware": self.cameraFirmwareVersion
                        }
                    })

                # ─── RECEIVED 3: MOUNTPOINT GENERATED DYNAMICALLY ───
                elif transaction_intent == "inject" and janus_event == "success":
                    plugin_data = raw_msg.get("plugindata", {}).get("data", {})
                    if plugin_data.get("streaming") == "created":
                        # CRITICAL FIX: Extracting the transient stream ID dynamically from the response body context
                        self.dynamic_stream_id = plugin_data["stream"]["id"]
                        logger.info(f"Received 3: Ingestion mountpoint ready. Dynamic Stream ID discovered: {self.dynamic_stream_id}")

                        # ─── SENT 4: INITIATE STREAM PLAYBACK ───
                        logger.info(f"Sent 4: Requesting subscription targeting ID: {self.dynamic_stream_id}")
                        await self.signal.send_json({
                            "session_id": self.session_id,
                            "janus": "message",
                            "transaction": self.getNextTransactionId("watch"),
                            "token": self.token,
                            "handle_id": self.handle_id,
                            "body": {
                                "request": "watch",
                                "id": self.dynamic_stream_id
                            }
                        })

                # ─── RECEIVED 4: WATCH COMMAND ACKNOWLEDGED ───
                elif transaction_intent == "watch" and janus_event == "ack":
                    logger.info("Received 4: Watch session acknowledged. Unblocking pipeline engine.")

                # ─── ASYNCHRONOUS INBOUND TRICKLE CANDIDATES ───
                elif janus_event == "trickle" and self.src_pc:
                    cand_data = raw_msg.get("candidate", {})
                    logger.info("Intercepted inbound remote ICE candidate trickle frame from Janus.")
                    if cand_data.get("completed") is True:
                        logger.info("Janus signaled candidate trickle is COMPLETED.")
                        candidates_done = True
                        # Dispatched the deferred start command only if our local SDP answer is prepared
                        if local_answer_desc is not None:
                            logger.info("Sending deferred 'start' message after completed trickle frame validation.")
                            await self.signal.send_json({
                                "session_id": self.session_id,
                                "janus": "message",
                                "transaction": self.getNextTransactionId("jsep_answer"),
                                "token": self.token,
                                "handle_id": self.handle_id,
                                "body": {
                                    "request": "start"
                                },
                                "jsep": {
                                    "type": local_answer_desc.type,
                                    "sdp": local_answer_desc.sdp
                                }
                            })
                            # Clear the storage object so we don't accidentally double-send later
                            local_answer_desc = None
                        else:
                            logger.warning("Trickle completion arrived before local client SDP answer was compiled.")
                    elif "candidate" in cand_data:
                        line = cand_data["candidate"].replace("candidate:", "", 1)
                        try:
                            ice_obj = candidate_from_sdp(line)
                            ice_obj.sdpMid = cand_data.get("sdpMid")
                            ice_obj.sdpMLineIndex = cand_data.get("sdpMLineIndex")
                            await self.src_pc.addIceCandidate(ice_obj)
                        except Exception as parse_exc:
                            logger.error(f"Failed to append remote ICE candidate object: {parse_exc}")

                # ─── ASYNCHRONOUS SDP RE-NEGOTIATION OFFER ───
                elif janus_event == "event" and "jsep" in raw_msg:
                    jsep = raw_msg["jsep"]
                    if jsep.get("type") == "offer" and self.src_pc:
                        logger.info("--- Asynchronous JSEP SDP Offer Intercepted ---")
                        remote_desc = RTCSessionDescription(type=jsep["type"], sdp=jsep["sdp"])
                        await self.src_pc.setRemoteDescription(remote_desc)

                        # Generate the local client response answer
                        local_answer_desc = await self.src_pc.createAnswer()
                        await self.src_pc.setLocalDescription(local_answer_desc)

                        # ─── SENT ANSWER: EMIT RESPONSE IN 'START' REQUEST ───
                        # if candidates_done:
                        logger.info("Submitting localized client JSEP SDP Answer back inside 'start' request container.")
                        await self.signal.send_json({
                                "session_id": self.session_id,
                                "janus": "message",
                                "transaction": self.getNextTransactionId("jsep_answer"),
                                "token": self.token,
                                "handle_id": self.handle_id,
                                "body": {
                                    "request": "start"
                                },
                                "jsep": {
                                    "type": local_answer_desc.type,
                                    "sdp": local_answer_desc.sdp
                                }
                            })
                        # Clear the storage object so we don't accidentally double-send later
                        local_answer_desc = None
        except Exception as loop_exc:
            logger.error(f"Anomaly encountered in direct orchestration thread loop: {loop_exc}")

    async def __janus_keepalive_loop(self) -> None:
        """
        Continuously pushes Janus session keepalives to prevent the remote
        gateway proxy from reaping our session context window.
        """
        logger.info("Janus transaction session heartbeat keepalive thread started...")
        try:
            # Janus sessions time out after 60 seconds of complete silence.
            # Sending a keepalive every 25-30 seconds matches standard browser behaviors perfectly.
            while self.is_running and not self.signal.closed:
                await asyncio.sleep(25.0)

                # Keepalives are only valid once the core session_id is generated by Sent 1 / Recieved 1
                if self.session_id:
                    logger.info(f"Sending Session Keepalive: {self.session_id}")
                    await self.signal.send_json({
                        "session_id": self.session_id,
                        "janus": "keepalive",
                        "transaction": self.getNextTransactionId("keepalive"),
                        "token": self.token
                    })
        except asyncio.CancelledError:
            return
        except Exception as e:
            logger.error(f"Error caught inside the Janus session keepalive monitor routine: {e}")


    async def tear_down_pipeline(self) -> None:
        """Gracefully disconnects and unsubscribes resource frames cleanly (Sent Detach / Destroy)."""
        self.is_running = False

        if self._keepalive_task:
            self._keepalive_task.cancel()
            try:
                await self._keepalive_task
            except asyncio.CancelledError:
                pass
            self._keepalive_task = None

        if self.session_id and self.handle_id:
            logger.info("Tearing down remote stream contexts... Submitting detach framework instructions.")
            try:
                await self.signal.send_json({
                    "session_id": self.session_id,
                    "janus": "detach",
                    "transaction": self.getNextTransactionId("cleanup_detach"),
                    "token": self.token,
                    "handle_id": self.handle_id
                    })
                await self.signal.send_json({
                    "session_id": self.session_id,
                    "janus": "destroy",
                    "transaction": self.getNextTransactionId("cleanup_destroy"),
                    "token": self.token
                })
            except Exception as cleanup_exc:
                logger.debug(f"State cleanup exception encountered: {cleanup_exc}")